# Encoding helpers
# ---------------------------------------------------------------------------


def _camera_exif(rng: np.random.Generator) -> Image.Exif:
    exif = Image.Exif()
    exif[ExifTags.Base.Make] = "samsung"
    exif[ExifTags.Base.Model] = str(rng.choice(["SM-A146B", "SM-M326B", "SM-A057F"]))
    month, day, hour, minute, second = (int(rng.integers(lo, hi)) for lo, hi in
                                        ((1, 9), (10, 28), (9, 19), (10, 59), (10, 59)))
    stamp = f"2026:{month:02d}:{day:02d} {hour:02d}:{minute:02d}:{second:02d}"
    exif[ExifTags.Base.DateTime] = stamp
    exif.get_ifd(ExifTags.IFD.Exif)[ExifTags.Base.DateTimeOriginal] = stamp
    return exif


def _editor_exif(original: Image.Exif) -> Image.Exif:
    exif = Image.Exif()
    for tag, value in original.items():
        if tag != ExifTags.Base.ExifOffset:  # sub-IFD pointer; the sub-IFD is rebuilt below
            exif[tag] = value
    original_time = original.get_ifd(ExifTags.IFD.Exif).get(ExifTags.Base.DateTimeOriginal)
    if original_time:
        exif.get_ifd(ExifTags.IFD.Exif)[ExifTags.Base.DateTimeOriginal] = original_time
    exif[ExifTags.Base.Software] = "Adobe Photoshop 25.4 (Windows)"
    exif[ExifTags.Base.DateTime] = "2026:10:02 22:41:07"
    return exif


def _encode_jpeg(image: Image.Image, quality: int, exif: Optional[Image.Exif] = None) -> bytes:
    buffer = io.BytesIO()
    kwargs: dict[str, Any] = {"format": "JPEG", "quality": quality}
    if exif is not None:
        kwargs["exif"] = exif.tobytes()
    image.convert("RGB").save(buffer, **kwargs)
    return buffer.getvalue()


def _encode_png(image: Image.Image) -> bytes:
    buffer = io.BytesIO()
    image.convert("RGB").save(buffer, format="PNG")
    return buffer.getvalue()


def _decode(data: bytes) -> tuple[Image.Image, Image.Exif]:
    with Image.open(io.BytesIO(data)) as opened:
        opened.load()
        return opened.convert("RGB"), opened.getexif()


def _scaled(image: Image.Image, factor: float) -> Image.Image:
    width, height = image.size
    return image.resize((max(1, round(width * factor)), max(1, round(height * factor))), Image.Resampling.LANCZOS)


