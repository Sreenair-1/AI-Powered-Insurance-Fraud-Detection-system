"""Controlled tampering benchmark for the document forensics stage.

No source dataset maps claims to documents, so the forensics checks cannot be
evaluated against labeled real claim documents. This module builds the
closest honest substitute: it takes clean bill images (rendered synthetic
hospital/garage bills by default, or a folder of real bill images), applies
known edits to copies of them, and measures how often each forensic check
(ELA, copy-move, metadata) and the combined verdict flag the edited copies
versus the untouched ones.

Edits (ground truth "tampered"):
- `copy_move`: one whole line-item row is cloned over another row of the same
  bill (a cheap charge replaced by an expensive one).
- `splice`: the total-amount area is replaced by a patch cut from a different,
  differently-compressed bill.
- `amount_edit`: the total is painted over with paper colour and re-typed, and
  the original camera metadata is kept (a careful forger).
- `amount_edit_in_editor`: the same edit, saved the way an image editor does
  (editor Software tag, new modification time).

Benign variants (ground truth "untouched"): the original capture, a gallery
re-save at lower JPEG quality, a scanner-style downscale, and a PNG screenshot.

Every sample is also scored after a messaging-app style re-share (downscale,
JPEG quality 70, metadata stripped), which is how many claim documents
actually reach an insurer.

Limitations: rendered bills are cleaner than real photographs and the edits
are generated by this module, so the numbers describe these checks on these
edit types, not real-world forgery detection rates.
"""
from __future__ import annotations

import io
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Iterable, Optional

import numpy as np
from PIL import ExifTags, Image, ImageDraw, ImageFilter, ImageFont
from sklearn.metrics import roc_auc_score

from src.forensics.copy_move import compute_copy_move
from src.forensics.ela import compute_ela
from src.forensics.metadata import analyze_metadata
from src.forensics.tampering import evaluate_document_tampering

BENCHMARK_VERSION = 1
RANDOM_STATE = 42

TAMPER_TYPES = ("copy_move", "splice", "amount_edit", "amount_edit_in_editor")
BENIGN_TYPES = ("original", "recompressed", "downscaled", "screenshot_png")
CONDITIONS = ("as_submitted", "messaging_app")
METHODS = ("ela", "copy_move", "metadata", "combined_verdict")

CAPTURE_QUALITY = 88
PAPER = (250, 249, 245)
INK = (30, 30, 34)

Box = tuple[int, int, int, int]

_HOSPITALS = ("Sanjeevani Multispeciality Hospital", "Shree Sai Nursing Home", "City Care Hospital",
              "Arogya Medical Centre", "Lifeline Super Speciality Clinic", "Sunrise Motors Service Centre",
              "Balaji Auto Works", "Om Sai Car Care")
_CITIES = ("Pune", "Nagpur", "Indore", "Lucknow", "Jaipur", "Nashik", "Surat", "Bhopal")
_PATIENTS = ("Rahul Sharma", "Priya Patil", "Amit Verma", "Sneha Kulkarni", "Vikram Singh", "Anjali Desai",
             "Rohan Gupta", "Kavita Joshi", "Suresh Yadav", "Meena Iyer")
_ITEMS = ("Room charges", "Consultation", "Pharmacy", "Pathology tests", "X-Ray", "Nursing charges",
          "OT charges", "Surgeon fee", "Bumper replacement", "Labour charges", "Paint work", "Headlamp assembly",
          "Wheel alignment", "Consumables")


@dataclass(frozen=True)
class BillImage:
    """A clean source document plus the layout boxes the edits target."""

    name: str
    image: Image.Image
    total_box: Box
    row_boxes: list[Box]  # regions a copy-move edit clones between
    source: str  # "synthetic" or "folder"


@dataclass(frozen=True)
class BenchmarkSample:
    bill: str
    variant: str
    is_tampered: bool
    condition: str
    data: bytes


@dataclass
class SampleResult:
    bill: str
    variant: str
    is_tampered: bool
    condition: str
    flags: dict[str, bool]
    tampering_score: float
    signals: dict[str, float] = field(default_factory=dict)


