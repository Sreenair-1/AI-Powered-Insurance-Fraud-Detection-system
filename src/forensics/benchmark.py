def analyze_sample(sample: BenchmarkSample) -> SampleResult:
    """Run the production forensic checks and verdict on one sample's bytes."""
    ela = compute_ela(sample.data)
    copy_move = compute_copy_move(sample.data, visualize=False)
    metadata = analyze_metadata(sample.data)
    verdict = evaluate_document_tampering(ela=ela, copy_move=copy_move, metadata=metadata)
    return SampleResult(
        bill=sample.bill,
        variant=sample.variant,
        is_tampered=sample.is_tampered,
        condition=sample.condition,
        flags={
            "ela": bool(verdict.details["ela_anomaly"]),
            "copy_move": bool(verdict.details["copy_move_anomaly"]),
            "metadata": bool(verdict.details["metadata_anomaly"]),
            "combined_verdict": bool(verdict.is_tampered),
        },
        tampering_score=float(verdict.tampering_score),
        signals={
            "ela": float(ela.features.high_error_pixel_ratio),
            "copy_move": float(copy_move.features.max_cluster_size),
            "metadata": float(metadata.features.software_editing_indicator
                              + metadata.features.datetime_original_modified_mismatch),
            "combined_verdict": float(verdict.tampering_score),
        },
    )


def _rate(values: Iterable[bool]) -> Optional[float]:
    values = list(values)
    return (sum(values) / len(values)) if values else None


def _auc(labels: list[bool], scores: list[float]) -> Optional[float]:
    if len(set(labels)) < 2 or len(set(scores)) < 2:
        return None
    return float(roc_auc_score(labels, scores))


def detection_at_fpr(labels: list[bool], scores: list[float], max_fpr: float = 0.10) -> dict[str, Any]:
    """Best detection rate any `score >= t` threshold reaches with FPR <= `max_fpr`.

    Shows whether *some* threshold on the continuous signal would be usable,
    independent of the fixed thresholds the production verdict applies.
    """
    y = np.asarray(labels, dtype=bool)
    s = np.asarray(scores, dtype=float)
    best: dict[str, Any] = {"threshold": None, "detection_rate": 0.0, "false_positive_rate": 0.0}
    if not y.any() or y.all():
        return best
    for t in np.unique(s):
        flagged = s >= t
        fpr = float(flagged[~y].mean())
        tpr = float(flagged[y].mean())
        if fpr <= max_fpr and tpr > best["detection_rate"]:
            best = {"threshold": float(t), "detection_rate": tpr, "false_positive_rate": fpr}
    return best


def summarize(results: list[SampleResult]) -> dict[str, Any]:
    """Per condition: detection rate per edit type, false-positive rate per
    benign type, and per-method precision/recall/ROC-AUC."""
    by_condition: dict[str, Any] = {}
    for condition in CONDITIONS:
        rows = [r for r in results if r.condition == condition]
        if not rows:
            continue
        tampered = [r for r in rows if r.is_tampered]
        benign = [r for r in rows if not r.is_tampered]
        labels = [r.is_tampered for r in rows]
        methods = {}
        for method in METHODS:
            tp = sum(r.flags[method] for r in tampered)
            fp = sum(r.flags[method] for r in benign)
            scores = [r.signals[method] for r in rows]
            methods[method] = {
                "detection_rate": _rate(r.flags[method] for r in tampered),
                "false_positive_rate": _rate(r.flags[method] for r in benign),
                "precision": (tp / (tp + fp)) if (tp + fp) else None,
                "roc_auc_continuous": _auc(labels, scores),
                "best_detection_at_fpr_10": detection_at_fpr(labels, scores, 0.10),
            }
        by_condition[condition] = {
            "n_tampered": len(tampered),
            "n_untouched": len(benign),
            "methods": methods,
            "detection_rate_by_edit": {
                edit: {m: _rate(r.flags[m] for r in tampered if r.variant == edit) for m in METHODS}
                for edit in TAMPER_TYPES
            },
            "false_positive_rate_by_variant": {
                variant: {m: _rate(r.flags[m] for r in benign if r.variant == variant) for m in METHODS}
                for variant in BENIGN_TYPES
            },
            "mean_tampering_score": {
                "tampered": float(np.mean([r.tampering_score for r in tampered])) if tampered else None,
                "untouched": float(np.mean([r.tampering_score for r in benign])) if benign else None,
            },
        }
    return by_condition


def run_tampering_benchmark(
    n_bills: int = 30,
    seed: int = RANDOM_STATE,
    images_dir: Optional[Path] = None,
    progress: Optional[Callable[[int, int], None]] = None,
) -> dict[str, Any]:
    """Build the sample set, score every sample, and return the JSON-ready report."""
    rng = np.random.default_rng(seed)
    bills: Iterable[BillImage]
    if images_dir is not None:
        folder_bills = load_bill_folder(images_dir, rng)
        if len(folder_bills) < 2:
            raise ValueError(f"{images_dir} must contain at least 2 .jpg/.jpeg/.png bill images")
        bills, n_bills, source = folder_bills, len(folder_bills), "folder"
        donor = folder_bills[-1]
    else:
        # Rendered lazily; each bill's splice donor is the bill before it.
        bills = (render_synthetic_bill(rng, name=f"synthetic_bill_{i + 1:03d}") for i in range(n_bills))
        source = "synthetic_rendered_bills"
        donor = render_synthetic_bill(rng, name="splice_donor")

    # One bill's samples at a time, so memory stays flat however many bills run.
    total = n_bills * len(TAMPER_TYPES + BENIGN_TYPES) * len(CONDITIONS)
    results = []
    for bill in bills:
        for sample in samples_for_bill(bill, donor, rng):
            results.append(analyze_sample(sample))
            if progress is not None:
                progress(len(results), total)
        donor = bill

    return {
        "benchmark": "document_tampering",
        "version": BENCHMARK_VERSION,
        "seed": seed,
        "source": source,
        "n_bills": n_bills,
        "n_samples": len(results),
        "edit_types": list(TAMPER_TYPES),
        "untouched_variants": list(BENIGN_TYPES),
        "conditions": {
            "as_submitted": "File exactly as produced by the capture or the edit",
            "messaging_app": "Re-shared like a chat app: downscaled to 75%, JPEG quality 70, metadata stripped",
        },
        "results": summarize(results),
        "limitations": [
            "Bills are rendered by the benchmark, not photographed claim documents"
            if source != "folder" else "Edit regions on folder bills are random blocks, not the real total field",
            "Edits are generated by this module; real forgeries (re-typed bills, reprinted documents) "
            "can look different",
            "Untouched and edited copies are 50/50 here, so precision is far higher than it would be "
            "at real tampering rates",
        ],
    }
