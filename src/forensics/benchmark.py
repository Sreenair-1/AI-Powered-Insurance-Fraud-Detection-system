def _paste_copy_move(image: Image.Image, bill: BillImage, rng: np.random.Generator) -> Image.Image:
    out = image.copy()
    src_idx, dst_idx = rng.choice(len(bill.row_boxes), size=2, replace=False)
    src, dst = bill.row_boxes[src_idx], bill.row_boxes[dst_idx]
    if src[:2] == dst[:2]:  # random folder boxes can coincide; shift the target down
        height = src[3] - src[1]
        dst = (src[0], src[1] + height * 3, src[2], src[3] + height * 3)
    out.paste(out.crop(src), (dst[0], dst[1]))
    return out


def _splice(image: Image.Image, bill: BillImage, donor: BillImage) -> Image.Image:
    out = image.copy()
    donor_lowq, _ = _decode(_encode_jpeg(donor.image, quality=60))
    left, top, right, bottom = bill.total_box
    patch = donor_lowq.crop(donor.total_box).resize((right - left, bottom - top), Image.Resampling.BILINEAR)
    out.paste(patch, (left, top))
    return out


def _amount_edit(image: Image.Image, bill: BillImage, rng: np.random.Generator) -> Image.Image:
    out = image.copy()
    draw = ImageDraw.Draw(out)
    left, top, right, bottom = bill.total_box
    region = np.asarray(out.crop(bill.total_box))
    paper = tuple(int(v) for v in np.percentile(region.reshape(-1, 3), 90, axis=0))
    draw.rectangle(bill.total_box, fill=paper)
    size = max(12, int((bottom - top) * 0.8))
    draw.text((left + 6, top + 4), _amount_text(int(rng.integers(300, 2000)) * 50), font=_font(size), fill=INK)
    return out


def samples_for_bill(bill: BillImage, donor: BillImage, rng: np.random.Generator) -> list[BenchmarkSample]:
    """One clean bill -> captured bytes -> benign variants + edited copies, in both conditions."""
    exif = _camera_exif(rng)
    captured = _encode_jpeg(bill.image, CAPTURE_QUALITY, exif)
    working, working_exif = _decode(captured)

    variants: dict[str, tuple[bool, bytes]] = {
        "original": (False, captured),
        "recompressed": (False, _encode_jpeg(working, 75, working_exif)),
        "downscaled": (False, _encode_jpeg(_scaled(working, 0.7), 85, working_exif)),
        "screenshot_png": (False, _encode_png(working)),
        "copy_move": (True, _encode_jpeg(_paste_copy_move(working, bill, rng), CAPTURE_QUALITY, working_exif)),
        "splice": (True, _encode_jpeg(_splice(working, bill, donor), CAPTURE_QUALITY, working_exif)),
        "amount_edit": (True, _encode_jpeg(_amount_edit(working, bill, rng), CAPTURE_QUALITY, working_exif)),
        "amount_edit_in_editor": (
            True, _encode_jpeg(_amount_edit(working, bill, rng), CAPTURE_QUALITY, _editor_exif(working_exif))
        ),
    }
    samples = []
    for variant, (tampered, data) in variants.items():
        samples.append(BenchmarkSample(bill.name, variant, tampered, "as_submitted", data))
        reshared, _ = _decode(data)
        samples.append(BenchmarkSample(
            bill.name, variant, tampered, "messaging_app", _encode_jpeg(_scaled(reshared, 0.75), 70)
        ))
    return samples


