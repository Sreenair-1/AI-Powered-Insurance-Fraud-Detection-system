def _font(size: int) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    return ImageFont.load_default(size=size)


def _amount_text(value: int) -> str:
    return f"Rs. {value:,}.00"


def render_synthetic_bill(rng: np.random.Generator, name: str = "bill") -> BillImage:
    """Render one hospital/garage bill with realistic layout and capture noise."""
    width, height = 900, 1200
    image = Image.new("RGB", (width, height), PAPER)
    draw = ImageDraw.Draw(image)
    title, small, body, bold = _font(30), _font(16), _font(20), _font(24)

    def num(lo: int, hi: int) -> int:
        return int(rng.integers(lo, hi))

    draw.text((60, 50), str(rng.choice(_HOSPITALS)), font=title, fill=INK)
    draw.text((60, 95), f"{num(10, 300)}, MG Road, {rng.choice(_CITIES)} - {num(400001, 499999)}", font=small, fill=INK)
    draw.text((60, 118), f"GSTIN 27AAB{num(1000, 9999)}C1Z{num(1, 9)}  Ph: +91 9{num(100000000, 999999999)}",
              font=small, fill=INK)
    draw.line((60, 150, width - 60, 150), fill=INK, width=2)
    draw.text((60, 170), f"Bill No: INV/{num(2025, 2027)}/{num(1000, 99999)}", font=body, fill=INK)
    draw.text((520, 170), f"Date: {num(1, 28):02d}/{num(1, 12):02d}/2026", font=body, fill=INK)
    draw.text((60, 205), f"Name: {rng.choice(_PATIENTS)}", font=body, fill=INK)
    draw.text((520, 205), f"Ref: CLM{num(100000, 999999)}", font=body, fill=INK)

    draw.rectangle((60, 260, width - 60, 300), outline=INK, width=2)
    draw.text((75, 270), "Particulars", font=body, fill=INK)
    draw.text((640, 270), "Amount", font=body, fill=INK)

    n_items = num(5, 9)
    items = rng.choice(_ITEMS, size=n_items, replace=False)
    amounts = [num(3, 400) * 50 for _ in range(n_items)]
    row_boxes: list[Box] = []
    y = 320
    for item, amount in zip(items, amounts, strict=True):
        draw.text((75, y), str(item), font=body, fill=INK)
        draw.text((640, y), _amount_text(amount), font=body, fill=INK)
        row_boxes.append((62, y - 8, width - 62, y + 34))
        draw.line((60, y + 38, width - 60, y + 38), fill=(200, 200, 200), width=1)
        y += 50

    draw.line((60, y + 10, width - 60, y + 10), fill=INK, width=2)
    draw.text((75, y + 30), "Total payable", font=bold, fill=INK)
    total = _amount_text(sum(amounts))
    draw.text((620, y + 30), total, font=bold, fill=INK)
    left, top, right, bottom = draw.textbbox((620, y + 30), total, font=bold)
    total_box = (left - 6, top - 6, right + 6, bottom + 6)

    draw.text((75, y + 110), "Received with thanks. Subject to local jurisdiction.", font=small, fill=INK)
    stamp_x, stamp_y = 600, y + 150
    draw.ellipse((stamp_x, stamp_y, stamp_x + 180, stamp_y + 110), outline=(40, 60, 160), width=4)
    draw.text((stamp_x + 40, stamp_y + 42), "PAID", font=title, fill=(40, 60, 160))
    draw.text((75, y + 220), "Authorised signatory", font=small, fill=INK)

    # Phone-capture realism: slight blur, uneven lighting, sensor noise.
    image = image.filter(ImageFilter.GaussianBlur(radius=0.6))
    arr = np.asarray(image, dtype=np.float32)
    gradient = np.linspace(1.0, 0.94, height, dtype=np.float32)[:, None, None]
    arr = arr * gradient + rng.normal(0.0, 2.5, size=arr.shape).astype(np.float32)
    image = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))
    return BillImage(name=name, image=image, total_box=total_box, row_boxes=row_boxes, source="synthetic")


def load_bill_folder(folder: Path, rng: np.random.Generator) -> list[BillImage]:
    """Load clean bill images from `folder`; edit regions are chosen at random.

    The layout of a real bill is unknown, so the "total" and copy-move boxes
    are random blocks in the lower-right half of the page, where totals
    usually sit.
    """
    bills = []
    for path in sorted(folder.iterdir()):
        if path.suffix.lower() not in {".jpg", ".jpeg", ".png"}:
            continue
        with Image.open(path) as opened:
            image = opened.convert("RGB")
        boxes = [_random_lower_right_box(image.size, rng) for _ in range(5)]
        bills.append(BillImage(name=path.stem, image=image, total_box=boxes[0], row_boxes=boxes[1:], source="folder"))
    return bills


def _random_lower_right_box(size: tuple[int, int], rng: np.random.Generator) -> Box:
    width, height = size
    bw, bh = max(24, width // 6), max(16, height // 30)
    x = int(rng.integers(width // 2, max(width // 2 + 1, width - bw - 1)))
    y = int(rng.integers(height // 3, max(height // 3 + 1, height - bh - 1)))
    return (x, y, x + bw, y + bh)


